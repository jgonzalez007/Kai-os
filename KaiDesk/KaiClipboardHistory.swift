import Foundation

public struct KaiClipboardEntry: Codable, Equatable, Identifiable, Sendable {
    public let id: UUID
    public var text: String
    public var date: Date
    public var sourceBundleID: String?
    public var pinned: Bool

    public init(id: UUID = UUID(), text: String, date: Date, sourceBundleID: String? = nil, pinned: Bool = false) {
        self.id = id
        self.text = text
        self.date = date
        self.sourceBundleID = sourceBundleID
        self.pinned = pinned
    }

    /// One line for a list row.
    public var preview: String {
        let flat = text.split(whereSeparator: \.isNewline).map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }.joined(separator: " ")
        return flat.count > 140 ? String(flat.prefix(140)) + "…" : flat
    }
}

/// Decides which copies are never recorded.
public struct KaiClipboardPolicy: Equatable, Sendable {
    /// Password managers and keychain tools. Always ignored.
    public static let passwordManagers: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop", "com.dashlane.dashlanephone", "com.lastpass.lastpassmacdesktop",
        "org.keepassxc.keepassxc", "com.apple.keychainaccess", "com.apple.Passwords",
        "com.nordsec.nordpass", "com.enpass.Enpass", "in.sinew.Enpass-Desktop"
    ]

    public static let terminals: Set<String> = [
        "com.apple.Terminal", "com.googlecode.iterm2", "com.mitchellh.ghostty",
        "dev.warp.Warp-Stable", "net.kovidgoyal.kitty", "org.alacritty",
        "com.github.wez.wezterm", "co.zeit.hyper", "io.alacritty"
    ]

    /// Dictation and speech tools put transcripts on the pasteboard.
    public static let dictation: Set<String> = [
        "com.apple.speech.SpeechRecognitionCore", "com.apple.SpeechRecognitionCore",
        "com.apple.assistant_service", "com.apple.dictation", "com.superwhisper.macos",
        "com.electron.wispr-flow", "com.ejzcr.macwhisper"
    ]

    /// Pasteboard types that apps use to mark a copy as secret or machine-made.
    public static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword"
    ]

    public var ignoreTerminals: Bool
    public var extraIgnoredBundleIDs: Set<String>

    public init(ignoreTerminals: Bool = true, extraIgnoredBundleIDs: Set<String> = []) {
        self.ignoreTerminals = ignoreTerminals
        self.extraIgnoredBundleIDs = extraIgnoredBundleIDs
    }

    public func isIgnored(bundleID: String?) -> Bool {
        guard let id = bundleID else { return false }
        if Self.passwordManagers.contains(id) || Self.dictation.contains(id) { return true }
        if ignoreTerminals && Self.terminals.contains(id) { return true }
        return extraIgnoredBundleIDs.contains(id)
    }

    public func hasSkippedType(_ types: [String]) -> Bool {
        types.contains { Self.skippedTypes.contains($0) }
    }
}

public struct KaiClipboardHistory: Codable, Equatable, Sendable {
    public static let capacity = 50
    /// Longer copies are left out. A huge paste is rarely wanted again and costs memory.
    public static let maxLength = 20_000

    public private(set) var entries: [KaiClipboardEntry]

    public init(entries: [KaiClipboardEntry] = []) {
        self.entries = entries
    }

    /// Records a copy. Returns true when the list changed.
    /// Skips: ignored apps, secret-marked copies, empty or one-character text, and over-long text.
    /// A repeat of an existing copy moves it to the top instead of adding a second row.
    @discardableResult
    public mutating func record(
        _ text: String,
        from sourceBundleID: String?,
        pasteboardTypes: [String] = [],
        policy: KaiClipboardPolicy = KaiClipboardPolicy(),
        now: Date = Date()
    ) -> Bool {
        if policy.isIgnored(bundleID: sourceBundleID) || policy.hasSkippedType(pasteboardTypes) { return false }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard trimmed.count > 1, text.count <= Self.maxLength else { return false }

        if let index = entries.firstIndex(where: { $0.text == text }) {
            // A repeat of the newest copy changes nothing visible.
            var entry = entries.remove(at: index)
            entry.date = now
            entries.insert(entry, at: 0)
            return index != 0
        }
        entries.insert(KaiClipboardEntry(text: text, date: now, sourceBundleID: sourceBundleID), at: 0)
        trim()
        return true
    }

    /// Moves an entry to the top, as if it were copied again.
    public mutating func bump(_ id: UUID, now: Date = Date()) {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        var entry = entries.remove(at: index)
        entry.date = now
        entries.insert(entry, at: 0)
    }

    public mutating func togglePin(_ id: UUID) {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        entries[index].pinned.toggle()
    }

    public mutating func remove(_ id: UUID) {
        entries.removeAll { $0.id == id }
    }

    /// Clears everything except pinned entries, unless `includingPinned`.
    public mutating func clear(includingPinned: Bool = false) {
        entries = includingPinned ? [] : entries.filter(\.pinned)
    }

    public func matching(_ query: String) -> [KaiClipboardEntry] {
        let q = query.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !q.isEmpty else { return entries }
        return entries.filter { $0.text.localizedCaseInsensitiveContains(q) }
    }

    /// Keeps the newest unpinned entries up to the capacity. Pinned entries never count against it.
    private mutating func trim() {
        var unpinned = 0
        entries = entries.filter { entry in
            if entry.pinned { return true }
            unpinned += 1
            return unpinned <= Self.capacity
        }
    }
}
